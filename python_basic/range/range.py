#------ the range() function returns a sequence of numbers starting from 0 and increments by 1,
#------ and ends at a specified number

#------ using the range() function

for i in range(6):
  print(i) #------ outputs 0 1 2 3 4 5

#------ specify the start value of the range() function

for i in range(2,6):
  print(i) #------ outputs 2 3 4 5


#------ specify the increment value
for i in range(2,30,3):
  print(i) #------ outputs 2 5 8 11 14 17 20 23 26 29 


