#------ you can assign multiple values to multiple variables in one line
#------ make sure the number of variables match the number of values unless an error will occur
x,y,z = 'Orange','Banana','Cherry'
print(x)  #------ outputs Orange
print(y)  #------ outputs Banana
print(z)  #------ outputs Cherry

#------ you can assign the same value to multiple variables in one line
x = y = z = 'Orange'
print(x)  #------ outputs Orange
print(y)  #------ outputs Orange
print(z)  #------ outputs Orange

