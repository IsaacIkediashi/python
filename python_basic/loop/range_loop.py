cities = ['New York City','London','Tokyo','Accra','Mexico City','Santiago']

# Using a range() function to loop through a list

#It creates a range equal to the index numbers of the list values in the cities variable

for city in range(len(cities)): 
  print(cities[city]) #------ New York City London Tokyo Accra Mexico City Santiago 